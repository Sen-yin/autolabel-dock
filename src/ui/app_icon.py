"""Application icon loader — single source of truth for the window/taskbar/exe icon.

Both the runtime (``main.py``) and the PyInstaller build (``autolabel.spec``)
need the same .ico. This module resolves the icon path in a way that works
in both contexts:

  - Normal (dev / venv) run:  ``<repo>/resources/icons/app.ico``
  - PyInstaller one-file:     ``sys._MEIPASS/resources/icons/app.ico``
  - PyInstaller one-dir:      ``sys._MEIPASS/resources/icons/app.ico``

The .ico is multi-resolution (16/24/32/48/64/128/256), generated by
``tools/build_icon.py`` from ``resources/icons/app_icon.png``. Run that
script whenever the source PNG changes — it is the only manual step.

Why also set it on ``QApplication`` (not just ``MainWindow``):
    ``QApplication.setWindowIcon`` is the icon Windows uses for the taskbar
    and the Alt-Tab switcher. ``MainWindow.setWindowIcon`` only overrides
    the title-bar icon. We want all three (title bar, taskbar, Alt-Tab)
    to match, so both calls are needed.
"""
from __future__ import annotations

import sys
from functools import lru_cache
from pathlib import Path

from PyQt5.QtGui import QIcon


_ICON_REL_PATH = Path("resources") / "icons" / "app.ico"


@lru_cache(maxsize=1)
def app_icon_path() -> Path:
    """Resolve the on-disk path of the application .ico.

    Result is cached so PyInstaller's ``sys._MEIPASS`` lookup runs once.
    """
    # PyInstaller (both --onefile and --onedir) extracts bundled data to
    # ``sys._MEIPASS`` at runtime and the spec puts resources/ alongside it.
    meipass = getattr(sys, "_MEIPASS", None)
    if meipass:
        candidate = Path(meipass) / _ICON_REL_PATH
        if candidate.exists():
            return candidate

    # Dev / venv run: walk up from this file until we find ``resources/``.
    # ``main.py`` is repo root, but tests / packaged wheels may import from
    # elsewhere, so be robust.
    here = Path(__file__).resolve()
    for ancestor in (here.parent, *here.parents):
        candidate = ancestor / _ICON_REL_PATH
        if candidate.exists():
            return candidate

    # Fall back to a sibling of the module — last resort so the call site
    # doesn't crash even if the file went missing during packaging.
    return here.parent / _ICON_REL_PATH


def load_app_icon() -> QIcon:
    """Build a QIcon for the application from the bundled .ico.

    Returns an empty QIcon (rather than raising) if the file is missing —
    Qt handles the absence gracefully and falls back to the platform default.
    Raising at startup would block every dev who hasn't run build_icon.py.
    """
    path = app_icon_path()
    if not path.exists():
        return QIcon()
    return QIcon(str(path))
